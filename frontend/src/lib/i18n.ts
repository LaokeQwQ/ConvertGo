export const catalogs: Record<Locale, Record<MessageKey, string>> = { 'en-US': en, 'zh-CN': zh }

export function resolveLocale(languages: readonly string[] = []): Locale {
  for (const language of languages) {
    const normalized = language.toLowerCase()
    if (normalized === 'zh-cn') return 'zh-CN'
    if (normalized === 'en-us') return 'en-US'
  }
  return 'zh-CN'
}

export function translator(locale: Locale) {
  return (key: MessageKey, values: Record<string, string | number> = {}): string =>
    catalogs[locale][key].replace(/\{(\w+)\}/g, (match, name: string) => String(values[name] ?? match))
}
